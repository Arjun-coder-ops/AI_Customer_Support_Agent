import json
import logging
from typing import Dict, Any, List

from evaluation.baselines.majority import MajorityBaselineClassifier
from evaluation.baselines.tfidf_logreg import TFIDFLogisticRegressionBaseline
from src.intent.classifier import FinalIntentClassifier

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# ISSUE 4 FIX — Intent evaluation pipeline
# ---------------------------------------------------------------------------
# PROBLEM: When golden_set.jsonl is empty or has only 1 provisional sample,
# the code fell back to X_test = X_train, evaluating the model on its own
# training data. This caused accuracy = 1.0 for the TF-IDF and Final
# classifiers — a meaningless metric.
#
# FIX: The evaluation now works in two modes:
#
# MODE A (preferred): Evaluate on TEST SPLIT using HEURISTIC labels.
#   - X_test comes from data/processed/test.jsonl
#   - y_test is generated by map_text_to_heuristic_intent (same heuristic
#     as used to generate training labels)
#   - THIS IS STILL A HEURISTIC BENCHMARK, not a gold one.
#   - Labels are generated by the SAME rule system as training labels.
#     Therefore accuracy reflects classifier-vs-heuristic agreement, not
#     human-judged accuracy.
#   - Dataset: REAL DATASET (AmazonHelp test split, ~8,250 conversations)
#   - Label source: HEURISTIC (keyword rules, NOT human-labelled)
#   - Benchmark type: PROXY DIAGNOSTIC — "does the classifier learn the
#     heuristic rules?" This is measurable and honest but limited.
#
# MODE B (BLOCKED): Evaluate on human-labelled golden set.
#   - Requires data/golden/golden_set.jsonl with is_human_reviewed=true
#     entries and ground-truth intent labels.
#   - Currently BLOCKED — only 1 provisional, non-human-reviewed example.
#   - Will become the gold benchmark once 150–250 examples are reviewed.
#
# KEY LIMITATION: Because training labels and test labels are BOTH generated
# by the same heuristic, a classifier that memorizes the heuristic will score
# 1.0. The FinalIntentClassifier uses the same TF-IDF features as the heuristic
# keywords, so high accuracy is expected and does NOT prove ML generalization.
# ---------------------------------------------------------------------------

def map_text_to_heuristic_intent(msg: str) -> str:
    """
    Heuristic keyword-based intent label.
    Used for BOTH training labels and test labels when no human labels exist.
    This means accuracy measures classifier-heuristic agreement, not
    classifier-human agreement.
    """
    msg_lower = msg.lower()
    if any(k in msg_lower for k in ["delay", "where is", "tracking", "late", "status"]):
        return "shipping_delay"
    elif any(k in msg_lower for k in ["missing", "incomplete"]):
        return "missing_item"
    elif any(k in msg_lower for k in ["cancel", "stop"]):
        return "order_cancellation"
    elif any(k in msg_lower for k in ["refund", "return", "back"]):
        return "refund_return_request"
    elif any(k in msg_lower for k in ["lock", "login", "password", "account"]):
        return "account_access_issue"
    elif any(k in msg_lower for k in ["charge", "paid", "double", "billing"]):
        return "payment_billing_issue"
    elif any(k in msg_lower for k in ["damage", "defect", "broken", "crack"]):
        return "product_defect_damage"
    return "general_inquiry_feedback"


def _load_human_golden_labels(golden_path: str) -> tuple:
    """
    Load only HUMAN-REVIEWED examples from the golden set.
    Returns (X_test, y_test, count_human_reviewed).
    Returns empty lists if no human-reviewed examples exist.
    """
    X_test, y_test = [], []
    if not os.path.exists(golden_path):
        return X_test, y_test, 0

    for line in open(golden_path, "r", encoding="utf-8"):
        if not line.strip():
            continue
        item = json.loads(line)
        msg = item.get("customer_message")
        is_human = item.get("is_human_reviewed", False)
        # Prefer explicit human_verified_intent; never treat heuristic seeds as human.
        intent = item.get("human_verified_intent") or (
            item.get("intent") if is_human else None
        )
        if msg and intent and is_human is True:
            X_test.append(msg)
            y_test.append(intent)

    return X_test, y_test, len(X_test)


def run_intent_evaluations(
    train_path: str = "data/processed/train.jsonl",
    test_path: str = "data/processed/test.jsonl",
    golden_path: str = "data/golden/golden_set.jsonl",
) -> Dict[str, Any]:
    """
    Run intent evaluation comparing Majority Baseline, TF-IDF Baseline, and Final Classifier.

    Evaluation is performed on the held-out TEST SPLIT with heuristic labels
    (Mode A), NOT on training data and NOT on the golden set until it is
    human-reviewed (Mode B).

    Labels are NOT human-labelled — they are heuristic. All metrics must be
    interpreted as "classifier-vs-heuristic-agreement" not true accuracy.
    """
    os.makedirs("results", exist_ok=True)
    logger.info("Starting Intent Classifier Evaluations...")

    # -----------------------------------------------------------------------
    # Load TRAINING data (for fitting baselines and final classifier)
    # -----------------------------------------------------------------------
    X_train, y_train = [], []
    if os.path.exists(train_path):
        for line in open(train_path, "r", encoding="utf-8"):
            if not line.strip():
                continue
            item = json.loads(line)
            msg = item.get("customer_initial_message", "")
            if msg:
                X_train.append(msg)
                y_train.append(map_text_to_heuristic_intent(msg))

    # Fallback if train is empty (structural tests only)
    if len(set(y_train)) < 2:
        X_train = [
            "My order #101 is delayed and late", "Missing item from my delivered box", "Cancel my active order",
            "Refund for damaged product", "Locked out of password account", "Double charged on card this morning",
            "Screen cracked on delivery box", "Restock information on store",
        ]
        y_train = [
            "shipping_delay", "missing_item", "order_cancellation",
            "refund_return_request", "account_access_issue", "payment_billing_issue",
            "product_defect_damage", "general_inquiry_feedback",
        ]

    # -----------------------------------------------------------------------
    # ISSUE 4 FIX: Load TEST SPLIT for evaluation (NOT training data)
    # The key change: test data comes from test.jsonl, never from X_train.
    # -----------------------------------------------------------------------
    X_test_heuristic, y_test_heuristic = [], []
    if os.path.exists(test_path):
        for line in open(test_path, "r", encoding="utf-8"):
            if not line.strip():
                continue
            item = json.loads(line)
            msg = item.get("customer_initial_message", "")
            if msg:
                X_test_heuristic.append(msg)
                y_test_heuristic.append(map_text_to_heuristic_intent(msg))

    # Human golden labels (SEPARATE evaluation track — never mixed into heuristic metrics)
    X_golden, y_golden, n_human_reviewed = _load_human_golden_labels(golden_path)
    golden_benchmark_status = (
        f"BLOCKED — REQUIRES HUMAN INPUT: Only {n_human_reviewed} human-reviewed examples exist "
        f"(need 150–250)."
        if n_human_reviewed < 150
        else f"ACTIVE — {n_human_reviewed} human-reviewed examples available."
    )

    # Primary evaluation is ALWAYS the heuristic held-out test split.
    # Human-golden evaluation is reported separately and never silently replaces it.
    X_eval, y_eval = X_test_heuristic, y_test_heuristic
    eval_source = (
        f"REAL_DATASET_TEST_SPLIT (data/processed/test.jsonl, {len(X_eval)} conversations)"
    )
    eval_label_type = "HEURISTIC — keyword rules, NOT human-labelled"

    if not X_eval:
        logger.error(
            "No evaluation data available on the held-out test split. "
            "Returning BLOCKED status."
        )
        blocked_output = {
            "evaluation_status": "BLOCKED — NO EVALUATION DATA",
            "golden_benchmark_status": golden_benchmark_status,
            "eval_source": eval_source,
            "eval_label_type": eval_label_type,
            "human_golden_evaluation": {
                "status": golden_benchmark_status,
                "human_reviewed_count": n_human_reviewed,
            },
        }
        with open("results/intent_results.json", "w", encoding="utf-8") as f:
            json.dump(blocked_output, f, indent=2)
        return blocked_output

    # -----------------------------------------------------------------------
    # Fit once on train; evaluate all models on the SAME heuristic test split
    # -----------------------------------------------------------------------
    maj_clf = MajorityBaselineClassifier()
    maj_clf.fit(y_train)
    maj_preds = maj_clf.predict(X_eval)
    maj_metrics = maj_clf.evaluate(y_eval, maj_preds)

    tfidf_clf = TFIDFLogisticRegressionBaseline()
    tfidf_clf.fit(X_train, y_train)
    tfidf_preds = tfidf_clf.predict(X_eval)
    tfidf_metrics = tfidf_clf.evaluate(y_eval, tfidf_preds)

    final_clf = FinalIntentClassifier()
    final_clf.fit(X_train, y_train)
    final_pred_objs = final_clf.predict_batch(X_eval)
    final_preds = [p["predicted_intent"] for p in final_pred_objs]
    final_metrics = tfidf_clf.evaluate(y_eval, final_preds)
    final_metrics["model"] = "FinalIntentClassifier"

    # -----------------------------------------------------------------------
    # Separate human-golden evaluation (only if human-reviewed labels exist)
    # -----------------------------------------------------------------------
    human_golden_evaluation: Dict[str, Any]
    if n_human_reviewed >= 150:
        maj_g = maj_clf.evaluate(y_golden, maj_clf.predict(X_golden))
        tfidf_g = tfidf_clf.evaluate(y_golden, tfidf_clf.predict(X_golden))
        final_g_preds = [
            p["predicted_intent"] for p in final_clf.predict_batch(X_golden)
        ]
        final_g = tfidf_clf.evaluate(y_golden, final_g_preds)
        final_g["model"] = "FinalIntentClassifier"
        human_golden_evaluation = {
            "status": "COMPLETED",
            "dataset_status": (
                f"HUMAN_GOLDEN_SET ({n_human_reviewed} human-reviewed examples)"
            ),
            "label_type": "HUMAN_LABELLED",
            "eval_sample_count": n_human_reviewed,
            "majority": maj_g,
            "tfidf_logreg": tfidf_g,
            "final_classifier": final_g,
            "note": (
                "This is a SEPARATE evaluation track from heuristic test-split "
                "metrics. Do not mix the two."
            ),
        }
    elif n_human_reviewed > 0:
        human_golden_evaluation = {
            "status": (
                f"PARTIAL — {n_human_reviewed} human-reviewed examples exist "
                f"(<{150} required). Metrics withheld until minimum is met."
            ),
            "human_reviewed_count": n_human_reviewed,
            "label_type": "HUMAN_LABELLED (insufficient count)",
        }
    else:
        human_golden_evaluation = {
            "status": golden_benchmark_status,
            "human_reviewed_count": 0,
            "label_type": "NONE — no human-reviewed golden labels",
        }

    dataset_caveat = (
        "IMPORTANT: Labels are generated by the SAME heuristic keyword rules used to "
        "assign training labels. High accuracy indicates the classifier learns the heuristic, "
        "NOT that it generalises to human-judged intent. A gold benchmark requires human labels. "
        "See human_golden_evaluation for the separate human track."
    )

    baselines_output = {
        "dataset_status": eval_source,
        "label_type": eval_label_type,
        "eval_sample_count": len(X_eval),
        "dataset_caveat": dataset_caveat,
        "golden_benchmark_status": golden_benchmark_status,
        "majority_baseline": maj_metrics,
        "tfidf_logreg_baseline": tfidf_metrics,
        "human_golden_evaluation": human_golden_evaluation,
    }
    with open("results/intent_baselines.json", "w", encoding="utf-8") as f:
        json.dump(baselines_output, f, indent=2)

    results_output = {
        "dataset_status": eval_source,
        "label_type": eval_label_type,
        "eval_sample_count": len(X_eval),
        "dataset_caveat": dataset_caveat,
        "golden_benchmark_status": golden_benchmark_status,
        "final_intent_classifier": final_metrics,
        "human_golden_evaluation": human_golden_evaluation,
    }
    with open("results/intent_results.json", "w", encoding="utf-8") as f:
        json.dump(results_output, f, indent=2)

    logger.info(
        "Intent evaluation complete. Eval source: %s. Label type: %s. Samples: %s.",
        eval_source,
        eval_label_type,
        len(X_eval),
    )
    return {
        "dataset_status": eval_source,
        "label_type": eval_label_type,
        "eval_sample_count": len(X_eval),
        "golden_benchmark_status": golden_benchmark_status,
        "majority": maj_metrics,
        "tfidf_logreg": tfidf_metrics,
        "final_classifier": final_metrics,
        "human_golden_evaluation": human_golden_evaluation,
    }


if __name__ == "__main__":
    import sys
    logging.basicConfig(level=logging.INFO, format="%(asctime)s - %(levelname)s - %(message)s")
    res = run_intent_evaluations()
    print(json.dumps(res, indent=2))
